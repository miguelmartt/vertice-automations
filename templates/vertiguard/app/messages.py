_language = "en"


def set_language(code):
    global _language
    if code not in TEXTS:
        raise ValueError(f"LANGUAGE must be one of {', '.join(TEXTS)}, not {code!r}")
    _language = code


def language():
    return _language


def t(key, **values):
    return TEXTS[_language][key].format(**values)


def plural(key, n, **values):
    return t(key + ("_1" if n == 1 else "_n"), n=n, **values)
